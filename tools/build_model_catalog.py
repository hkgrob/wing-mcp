#!/usr/bin/env python3
"""Build server/model_catalog.json from libwing's propmap.jsonl.

    python3 tools/build_model_catalog.py /path/to/libwing/propmap.jsonl

propmap.jsonl is from libwing (https://github.com/dannyfiresnake/libwing,
Apache-2.0 / MIT, see server/licenses/libwing-LICENSE.txt), generated by its
author from a WING on firmware 3.0.5. It lists every parameter of every
processing model, which a profile walk cannot: the walk only sees the model
loaded on each slot at the time. The catalog is reference data; the live
desk is always the authority for what a write is checked against.
"""
import json
import os
import re
import sys

FAMS = ["ch", "aux", "bus", "main", "mtx"]


def num(x):
    x = float(x)
    if abs(x - round(x)) < 1e-4:
        return "%d" % round(x)
    return ("%.4f" % x).rstrip("0").rstrip(".")


def desk_type(r):
    t, u = r["type"], (" " + r["unit"]) if r.get("unit") else ""
    if t in ("linear float", "log float"):
        k = "lin" if t == "linear float" else "log"
        s = "%s [%s .. %s%s]" % (k, num(r["minfloat"]), num(r["maxfloat"]), u)
        return s + (", %d steps" % r["steps"] if r.get("steps") else "")
    if t == "fader level":
        return "fader [-oo .. 10.0 dB], 1024 steps"
    if t == "integer":
        return "int [%d .. %d]" % (r.get("minint", 0), r.get("maxint", 0))
    if t in ("string enum", "float enum"):
        return "list [%s]" % ", ".join(str(i["item"]) if not isinstance(i["item"], float)
                                       else num(i["item"]) for i in r.get("items", []))
    if t == "string":
        return "string [%d]" % r.get("maxstringlen", 0)
    return t


def main(path):
    recs = {}
    for line in open(path, encoding="utf-8"):
        try:
            r = json.loads(line)
        except ValueError:
            continue
        recs[r["fullname"]] = r
    sections = {}

    def add(key, base, mdl_rec):
        models = {}
        for it in mdl_rec.get("items", []):
            m = str(it["item"])
            pre = "%s/%s/" % (base, m)
            params = {}
            for full, r in recs.items():
                if full.startswith(pre) and r["type"] != "node" and "/" not in full[len(pre):]:
                    params[r["name"]] = {"type": desk_type(r), "label": r.get("longname", "")}
            models[m] = {"label": it.get("longitem", m), "params": params}
        sections[key] = {"example_node": base, "models": models}

    for fam in FAMS:
        for full, r in recs.items():
            m = re.match(r"^/%s/1/([a-z]+)/mdl$" % fam, full)
            if m:
                add("%s/%s" % (fam, m.group(1)), "/%s/1/%s" % (fam, m.group(1)), r)
    if "/fx/1/mdl" in recs:
        add("fx", "/fx/1", recs["/fx/1/mdl"])
    out = {"source": "libwing propmap.jsonl (https://github.com/dannyfiresnake/libwing), "
                     "Apache-2.0/MIT; mapped on WING firmware 3.0.5",
           "note": "Reference only. The connected desk is the authority.",
           "sections": sections}
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "server", "model_catalog.json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, separators=(",", ":"), sort_keys=True)
    for k, v in sorted(sections.items()):
        print("%-10s %3d models  %4d params" % (k, len(v["models"]),
                                             sum(len(m["params"]) for m in v["models"].values())))
    print("wrote", os.path.normpath(dst), os.path.getsize(dst), "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
